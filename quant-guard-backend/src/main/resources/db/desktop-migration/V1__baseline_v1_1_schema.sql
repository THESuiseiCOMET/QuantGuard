    CONSTRAINT chk_simulated_trade_side CHECK (side IN ('BUY', 'SELL')),
    CONSTRAINT chk_simulated_trade_quantity CHECK (quantity > 0),
    CONSTRAINT chk_simulated_trade_execution_price CHECK (execution_price > 0),
    CONSTRAINT chk_simulated_trade_amount CHECK (trade_amount > 0)
);

CREATE INDEX idx_simulated_trade_account_id ON simulated_trade (account_id);
CREATE INDEX idx_simulated_trade_portfolio_id ON simulated_trade (portfolio_id);
CREATE INDEX idx_simulated_trade_instrument_id ON simulated_trade (instrument_id);

CREATE TABLE cash_ledger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    portfolio_id BIGINT NOT NULL,
    order_id BIGINT NOT NULL,
    trade_id BIGINT,
    entry_type VARCHAR(30) NOT NULL,
    available_cash_delta DECIMAL(19,4) NOT NULL,
    frozen_cash_delta DECIMAL(19,4) NOT NULL,
    available_cash_after DECIMAL(19,4) NOT NULL,
    frozen_cash_after DECIMAL(19,4) NOT NULL,
    description VARCHAR(255),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_cash_ledger_order_entry_type UNIQUE (order_id, entry_type),
    CONSTRAINT fk_cash_ledger_account
        FOREIGN KEY (account_id) REFERENCES simulation_account (id),
    CONSTRAINT fk_cash_ledger_portfolio
        FOREIGN KEY (portfolio_id) REFERENCES investment_portfolio (id),
    CONSTRAINT fk_cash_ledger_order
        FOREIGN KEY (order_id) REFERENCES simulated_order (id),
    CONSTRAINT fk_cash_ledger_trade
        FOREIGN KEY (trade_id) REFERENCES simulated_trade (id),
    CONSTRAINT chk_cash_ledger_entry_type
        CHECK (entry_type IN (
            'BUY_ORDER_FREEZE',
            'BUY_SETTLEMENT',
            'SELL_PROCEEDS',
            'BUY_CANCEL_RELEASE'
        )),
    CONSTRAINT chk_cash_ledger_available_after CHECK (available_cash_after >= 0),
    CONSTRAINT chk_cash_ledger_frozen_after CHECK (frozen_cash_after >= 0)
);

CREATE INDEX idx_cash_ledger_account_id ON cash_ledger (account_id);
CREATE INDEX idx_cash_ledger_portfolio_id ON cash_ledger (portfolio_id);
CREATE INDEX idx_cash_ledger_order_id ON cash_ledger (order_id);
CREATE INDEX idx_cash_ledger_trade_id ON cash_ledger (trade_id);

CREATE TABLE instrument_daily_price (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instrument_id BIGINT NOT NULL,
    trade_date DATE NOT NULL,
    open_price DECIMAL(19,4) NOT NULL,
    high_price DECIMAL(19,4) NOT NULL,
    low_price DECIMAL(19,4) NOT NULL,
    close_price DECIMAL(19,4) NOT NULL,
    previous_close DECIMAL(19,4),
    price_change DECIMAL(19,4),
    percentage_change DECIMAL(19,6),
    volume_lots DECIMAL(24,4) NOT NULL,
    amount_cny DECIMAL(24,4) NOT NULL,
    adjustment_type VARCHAR(20) NOT NULL DEFAULT 'NONE',
    data_source VARCHAR(32) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version INT NOT NULL DEFAULT 0,
    CONSTRAINT uk_daily_price_instrument_date_adjustment
        UNIQUE (instrument_id, trade_date, adjustment_type),
    CONSTRAINT fk_daily_price_instrument
        FOREIGN KEY (instrument_id) REFERENCES security_instrument (id),
    CONSTRAINT chk_daily_price_adjustment_type CHECK (adjustment_type IN ('NONE')),
    CONSTRAINT chk_daily_price_positive_prices
        CHECK (open_price > 0 AND high_price > 0 AND low_price > 0 AND close_price > 0),
    CONSTRAINT chk_daily_price_ohlc CHECK (
        high_price >= open_price
        AND high_price >= close_price
        AND high_price >= low_price
        AND low_price <= open_price
        AND low_price <= close_price
    ),
    CONSTRAINT chk_daily_price_volume_amount CHECK (volume_lots >= 0 AND amount_cny >= 0)
);

CREATE INDEX idx_daily_price_instrument_date
    ON instrument_daily_price (instrument_id, trade_date);

CREATE TABLE market_data_sync_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instrument_id BIGINT NOT NULL,
    provider VARCHAR(32) NOT NULL,
    sync_type VARCHAR(32) NOT NULL,
    requested_start_date DATE NOT NULL,
    requested_end_date DATE NOT NULL,
    records_received INT NOT NULL DEFAULT 0,
    records_inserted INT NOT NULL DEFAULT 0,
    records_updated INT NOT NULL DEFAULT 0,
    status VARCHAR(32) NOT NULL,
    error_message VARCHAR(512),
    started_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMP(6),
    CONSTRAINT fk_market_data_sync_log_instrument
        FOREIGN KEY (instrument_id) REFERENCES security_instrument (id),
    CONSTRAINT chk_market_data_sync_log_status
        CHECK (status IN ('RUNNING', 'SUCCESS', 'PARTIAL_SUCCESS', 'FAILED'))
);

CREATE INDEX idx_market_data_sync_log_instrument_started
    ON market_data_sync_log (instrument_id, started_at);
