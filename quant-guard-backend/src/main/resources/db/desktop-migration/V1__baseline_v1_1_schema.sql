-- QuantGuard desktop migration V1: baseline the complete V1.1 business schema on H2 File.
-- Purpose: initializes a new desktop database without requiring MySQL.
-- Objects: creates all V1.1 account, portfolio, instrument, position, order, trade, ledger,
--          legacy risk-config, daily-price, and market-data sync tables with their constraints.
-- Execution order: first Flyway migration for the desktop profile.
-- Repeatable: no; Flyway records this version and applies it exactly once per desktop database.
-- Data safety: creates a new schema only and does not drop, delete, or overwrite user data.
-- Secrets: contains no passwords, tokens, API keys, machine paths, or private trading data.
-- Execution: applied automatically only when the Spring desktop profile is active.

CREATE TABLE simulation_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_name VARCHAR(64) NOT NULL,
    account_type VARCHAR(20) NOT NULL,
    initial_cash DECIMAL(19,4) NOT NULL,
    available_cash DECIMAL(19,4) NOT NULL,
    frozen_cash DECIMAL(19,4) NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version INT NOT NULL DEFAULT 0,
    CONSTRAINT uk_simulation_account_name UNIQUE (account_name),
    CONSTRAINT chk_simulation_account_type CHECK (account_type IN ('LONG_TERM', 'SHORT_TERM')),
    CONSTRAINT chk_simulation_account_status CHECK (status IN ('ACTIVE', 'DISABLED')),
    CONSTRAINT chk_simulation_account_initial_cash CHECK (initial_cash >= 0),
    CONSTRAINT chk_simulation_account_available_cash CHECK (available_cash >= 0),
    CONSTRAINT chk_simulation_account_frozen_cash CHECK (frozen_cash >= 0)
);

CREATE TABLE investment_portfolio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    portfolio_name VARCHAR(64) NOT NULL,
    portfolio_type VARCHAR(20) NOT NULL,
    description VARCHAR(255),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_investment_portfolio_account_name UNIQUE (account_id, portfolio_name),
    CONSTRAINT fk_investment_portfolio_account
        FOREIGN KEY (account_id) REFERENCES simulation_account (id),
    CONSTRAINT chk_investment_portfolio_type CHECK (portfolio_type IN ('LONG_TERM', 'SHORT_TERM')),
    CONSTRAINT chk_investment_portfolio_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE INDEX idx_investment_portfolio_account_id
    ON investment_portfolio (account_id);

CREATE TABLE security_instrument (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol VARCHAR(32) NOT NULL,
    exchange VARCHAR(20) NOT NULL,
    instrument_name VARCHAR(128) NOT NULL,
    asset_type VARCHAR(20) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    lot_size DECIMAL(19,6) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_security_instrument_exchange_symbol UNIQUE (exchange, symbol),
    CONSTRAINT chk_security_instrument_exchange
        CHECK (exchange IN ('SSE', 'SZSE', 'BSE', 'HKEX', 'NASDAQ', 'NYSE')),
    CONSTRAINT chk_security_instrument_asset_type CHECK (asset_type IN ('STOCK', 'ETF', 'INDEX')),
    CONSTRAINT chk_security_instrument_status CHECK (status IN ('ACTIVE', 'DISABLED')),
    CONSTRAINT chk_security_instrument_lot_size CHECK (lot_size > 0)
);

CREATE INDEX idx_security_instrument_symbol
    ON security_instrument (symbol);

CREATE TABLE portfolio_position (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id BIGINT NOT NULL,
    instrument_id BIGINT NOT NULL,
    total_quantity DECIMAL(19,6) NOT NULL DEFAULT 0,
    available_quantity DECIMAL(19,6) NOT NULL DEFAULT 0,
    frozen_quantity DECIMAL(19,6) NOT NULL DEFAULT 0,
    average_cost DECIMAL(19,4) NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version INT NOT NULL DEFAULT 0,
    CONSTRAINT uk_portfolio_position_portfolio_instrument UNIQUE (portfolio_id, instrument_id),
    CONSTRAINT fk_portfolio_position_portfolio
        FOREIGN KEY (portfolio_id) REFERENCES investment_portfolio (id),
    CONSTRAINT fk_portfolio_position_instrument
        FOREIGN KEY (instrument_id) REFERENCES security_instrument (id),
    CONSTRAINT chk_portfolio_position_total_quantity CHECK (total_quantity >= 0),
    CONSTRAINT chk_portfolio_position_available_quantity CHECK (available_quantity >= 0),
    CONSTRAINT chk_portfolio_position_frozen_quantity CHECK (frozen_quantity >= 0),
    CONSTRAINT chk_portfolio_position_average_cost CHECK (average_cost >= 0),
    CONSTRAINT chk_portfolio_position_quantity_balance
        CHECK (available_quantity + frozen_quantity <= total_quantity)
);

CREATE INDEX idx_portfolio_position_portfolio_id
    ON portfolio_position (portfolio_id);
CREATE INDEX idx_portfolio_position_instrument_id
    ON portfolio_position (instrument_id);

CREATE TABLE portfolio_risk_config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id BIGINT NOT NULL,
    max_single_order_amount DECIMAL(19,4) NOT NULL,
    max_position_ratio DECIMAL(10,6) NOT NULL,
    allow_buy BOOLEAN NOT NULL DEFAULT TRUE,
    allow_sell BOOLEAN NOT NULL DEFAULT TRUE,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version INT NOT NULL DEFAULT 0,
    CONSTRAINT uk_portfolio_risk_config_portfolio UNIQUE (portfolio_id),
    CONSTRAINT fk_portfolio_risk_config_portfolio
        FOREIGN KEY (portfolio_id) REFERENCES investment_portfolio (id),
    CONSTRAINT chk_portfolio_risk_config_max_order CHECK (max_single_order_amount > 0),
    CONSTRAINT chk_portfolio_risk_config_position_ratio
        CHECK (max_position_ratio >= 0 AND max_position_ratio <= 1),
    CONSTRAINT chk_portfolio_risk_config_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE TABLE simulated_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no VARCHAR(40) NOT NULL,
    account_id BIGINT NOT NULL,
    portfolio_id BIGINT NOT NULL,
    instrument_id BIGINT NOT NULL,
    side VARCHAR(10) NOT NULL,
    order_type VARCHAR(20) NOT NULL,
    requested_quantity DECIMAL(19,6) NOT NULL,
    limit_price DECIMAL(19,4) NOT NULL,
    frozen_amount DECIMAL(19,4) NOT NULL DEFAULT 0,
    frozen_quantity DECIMAL(19,6) NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL,
    rejection_reason VARCHAR(255),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version INT NOT NULL DEFAULT 0,
    CONSTRAINT uk_simulated_order_order_no UNIQUE (order_no),
    CONSTRAINT fk_simulated_order_account
        FOREIGN KEY (account_id) REFERENCES simulation_account (id),
    CONSTRAINT fk_simulated_order_portfolio
        FOREIGN KEY (portfolio_id) REFERENCES investment_portfolio (id),
    CONSTRAINT fk_simulated_order_instrument
        FOREIGN KEY (instrument_id) REFERENCES security_instrument (id),
    CONSTRAINT chk_simulated_order_side CHECK (side IN ('BUY', 'SELL')),
    CONSTRAINT chk_simulated_order_type CHECK (order_type IN ('LIMIT')),
    CONSTRAINT chk_simulated_order_status CHECK (status IN ('OPEN', 'REJECTED', 'FILLED', 'CANCELED')),
    CONSTRAINT chk_simulated_order_quantity CHECK (requested_quantity > 0),
    CONSTRAINT chk_simulated_order_limit_price CHECK (limit_price > 0),
    CONSTRAINT chk_simulated_order_frozen_amount CHECK (frozen_amount >= 0),
    CONSTRAINT chk_simulated_order_frozen_quantity CHECK (frozen_quantity >= 0)
);

CREATE INDEX idx_simulated_order_account_id ON simulated_order (account_id);
CREATE INDEX idx_simulated_order_portfolio_id ON simulated_order (portfolio_id);
CREATE INDEX idx_simulated_order_instrument_id ON simulated_order (instrument_id);

CREATE TABLE simulated_trade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trade_no VARCHAR(40) NOT NULL,
    order_id BIGINT NOT NULL,
